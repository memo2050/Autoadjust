#!/usr/bin/env bash
# Regenerates supabase/migrations/ALL.sql from the numbered migration files (0100 and up), in order.
# ALL.sql is a convenience for pasting into a Supabase SQL Editor. It is NOT run automatically anywhere.
set -euo pipefail
cd "$(dirname "$0")/../supabase/migrations"
out=ALL.sql
first=$(ls 0[0-9][0-9][0-9]_*.sql | head -1); last=$(ls 0[0-9][0-9][0-9]_*.sql | tail -1)
{
  echo "-- ALL.sql: migrations ${first%%_*} to ${last%%_*} in order. GENERATED by scripts/build-migrations-all.sh: do not edit by hand (a test fails if it drifts)."
  echo "-- PREREQUISITE: the base schema files in supabase/ (schema.sql, 002_hosting.sql, app_records.sql, 003..008) must already exist, because 0105/0107 alter the soc_*/noc_* tables."
  echo "-- Each file is its own transaction and is repeatable. Review the individual files first. Do NOT run against production without the owner's approval and a backup."
  for f in 0[0-9][0-9][0-9]_*.sql; do echo; echo "-- ===== $f ====="; cat "$f"; done
} > "$out"
